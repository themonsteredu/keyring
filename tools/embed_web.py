#!/usr/bin/env python3
"""Create deterministic gzip assets: Arduino IDE needs no filesystem uploader."""
import argparse
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
         ".js": "text/javascript; charset=utf-8", ".mjs": "text/javascript; charset=utf-8",
         ".json": "application/json", ".svg": "image/svg+xml", ".png": "image/png",
         ".gif": "image/gif", ".cur": "image/x-icon", ".woff2": "font/woff2",
         ".txt": "text/plain; charset=utf-8"}


def web_files():
    files = {}
    for path in sorted((ROOT / "web").rglob("*")):
        if not path.is_file():
            continue
        mime = TYPES.get(path.suffix)
        if path.name in ("LICENSE", "NOTICE"):
            mime = "text/plain; charset=utf-8"
        if mime:
            files[path.relative_to(ROOT / "web").as_posix()] = mime
    return files


def generate():
    files = web_files()
    lines = ["// Generated by tools/embed_web.py; do not edit.", "#pragma once",
             "#include <Arduino.h>", "#include <stddef.h>", "#include <stdint.h>",
             "namespace web_assets {",
             "struct Asset { const char* path; const char* type; const uint8_t* data; size_t size; };"]
    for i, name in enumerate(files):
        compressed = gzip.compress((ROOT / "web" / name).read_bytes(), compresslevel=9, mtime=0)
        # Python versions disagree on the OS header byte. RFC1952 'unknown' is stable.
        compressed = compressed[:9] + b"\xff" + compressed[10:]
        lines.append(f"static const uint8_t asset_{i}[] PROGMEM = {{")
        for start in range(0, len(compressed), 20):
            lines.append("  " + ",".join(str(b) for b in compressed[start:start + 20]) + ",")
        lines.append("};")
    lines.append("static const Asset assets[] = {")
    for i, (name, mime) in enumerate(files.items()):
        path = "/" + name
        lines.append(f'  {{"{path}", "{mime}", asset_{i}, sizeof(asset_{i})}},')
    lines.extend(["};", "static const size_t assetCount = sizeof(assets) / sizeof(assets[0]);", "} // namespace web_assets", ""])
    return "\n".join(lines).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "firmware/Keyring/web_assets.h"
    content = generate()
    if args.check:
        if not target.exists() or target.read_bytes() != content:
            parser.exit(1, "Firmware web assets are stale: run python3 tools/embed_web.py\n")
        print("Firmware gzip assets match all web sources.")
    else:
        target.write_bytes(content)
        print(f"Embedded {len(web_files())} offline web assets ({len(content):,} header bytes).")


if __name__ == "__main__":
    main()
