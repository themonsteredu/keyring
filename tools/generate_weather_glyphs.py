#!/usr/bin/env python3
"""Emit the offline OLED font from its checked-in, licensed bitmap subset.

No font download or imaging package is needed to build the firmware. The source
JSON stores 10x12 Korean glyphs and purpose-drawn digits; bit zero is the left
pixel. Browser and firmware consume the same rows.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    source = json.loads((ROOT / "assets/oled-weather-glyphs.json").read_text())
    glyphs = source["glyphs"]
    header = ["#pragma once", "// Generated by tools/generate_weather_glyphs.py.",
              "// Korean subset: Noto Sans CJK KR, SIL OFL 1.1.",
              "// See docs/licenses/NotoSansCJK-OFL.txt.", "#include <stdint.h>",
              "namespace keyring { namespace weather_detail {",
              "struct Glyph { uint16_t code; uint8_t width; uint16_t rows[12]; };",
              "static const Glyph kGlyphs[] = {"]
    for char, glyph in sorted(glyphs.items(), key=lambda item: ord(item[0])):
        rows = ','.join(str(value) for value in glyph["rows"])
        header.append("  {%d,%d,{%s}}, // %s" % (ord(char), glyph["width"], rows, char))
    header.extend(["};", "} }", ""])
    js = "// Generated by tools/generate_weather_glyphs.py. Korean: SIL OFL 1.1.\n"
    js += "// See /licenses/NotoSansCJK-OFL.txt in the web build.\n"
    js += "export const WEATHER_GLYPHS = " + json.dumps(glyphs, ensure_ascii=False, separators=(',', ':')) + ";\n"
    license_text = (ROOT / "docs/licenses/NotoSansCJK-OFL.txt").read_text()
    return {ROOT / "firmware/Keyring/weather_glyphs.h": '\n'.join(header),
            ROOT / "web/weather-glyphs.mjs": js,
            ROOT / "web/licenses/NotoSansCJK-OFL.txt": license_text}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for destination, value in outputs().items():
        encoded = value.encode()
        if args.check:
            if not destination.exists() or destination.read_bytes() != encoded:
                parser.exit(1, f"{destination.relative_to(ROOT)} is stale; run tools/generate_weather_glyphs.py\n")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(encoded)
    print("OLED Korean glyph rows match firmware and browser." if args.check else "Generated OLED Korean font for firmware and browser.")


if __name__ == "__main__":
    main()
